#!/usr/bin/env bash
# Writes the licenses of every Go module inside the binary into web/assets/licenses/THIRD-PARTY.txt, which the program
# shows at /licenses: MIT, BSD and Apache all ask that their notice travels with the binary.
#
#   scripts/third-party-licenses.sh           write the file
#   scripts/third-party-licenses.sh --check   fail when the file does not match the modules (scripts/check.sh)
set -euo pipefail
cd "$(dirname "$0")/.."

target="web/assets/licenses/THIRD-PARTY.txt"
fail() { printf '✗ %s\n' "$1" >&2; exit 1; }

work="$(mktemp -d)"
trap 'rm -rf -- "$work"' EXIT
out="$work/THIRD-PARTY.txt"

# Only modules whose code is compiled into the program: test-only modules are not shipped. LC_ALL=C: the order must
# not depend on the locale of the machine.
modules="$(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/eightperday | LC_ALL=C sort -u)"
[[ -n "$modules" ]] || fail "go list named no modules: the check itself is broken"
{
    printf 'Licenses of the Go modules compiled into EightPerDay.\nGenerated by scripts/third-party-licenses.sh, do not edit.\n'
    printf '\n================================================================================\nThe Go standard library and runtime\n'
    printf '================================================================================\n\n'
    cat "$(go env GOROOT)/LICENSE"
    while read -r path version dir; do
        license=""
        for name in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING; do
            if [[ -f "$dir/$name" ]]; then
                license="$dir/$name"
                break
            fi
        done
        [[ -n "$license" ]] || fail "$path $version has no license file"
        printf '\n================================================================================\n%s %s\n' "$path" "$version"
        printf '================================================================================\n\n'
        cat "$license"
    done <<<"$modules"
} >"$out"

if [[ "${1:-}" == "--check" ]]; then
    cmp -s "$out" "$target" || fail "$target does not match the modules of the binary: run scripts/third-party-licenses.sh"
    echo "  third-party licenses complete ($(wc -l <<<"$modules") modules)"
else
    mkdir -p "$(dirname "$target")"
    cp "$out" "$target"
    echo "wrote $target ($(wc -l <<<"$modules") modules)"
fi
